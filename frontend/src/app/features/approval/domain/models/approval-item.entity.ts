/**
 * Approval Domain Entities and Types.
 *
 * Defines the core business model for Human-in-the-Loop review items
 * within OnboardIQ.
 */

/** Possible lifecycle decision states for an approval item */
export type ApprovalStatus = 'pending' | 'approved' | 'rejected';

/**
 * Domain entity representing an action awaiting human review or already audited.
 */
export interface ApprovalItem {
  /** Unique primary key ID of the approval record */
  id: number;

  /** Foreign key pointing to the associated onboarding case */
  caseId: number;

  /** Foreign key pointing to the triggering workflow step */
  stepId: number;

  /** User-friendly descriptive title for the review card */
  title: string;

  /** High-level summary of the action being requested */
  description: string;

  /** Classification tag of the action (e.g., 'document_review', 'provisioning') */
  actionType: string;

  /** Deep payload inspection data generated by AI or system integrations */
  previewData: any | null;

  /** Current audit decision state */
  decision: ApprovalStatus;

  /** Optional reviewer note, feedback, or justification */
  reviewerComment: string | null;

  /** ISO timestamp when the approval item was created */
  createdAt: string;

  /** ISO timestamp when the human reviewer submitted their decision */
  decidedAt: string | null;

  /** Optional human-readable step title for context display */
  stepLabel?: string;
}
